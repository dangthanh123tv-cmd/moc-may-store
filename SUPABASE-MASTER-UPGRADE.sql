-- 5) Chống spam cơ bản ở database: tối đa 3 review cùng tên trong 30 phút.
create or replace function public.prevent_review_spam()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.reviews r where lower(trim(r.name)) = lower(trim(new.name)) and r.created_at > now() - interval '30 minutes') >= 3 then
    raise exception 'Bạn đã gửi quá nhiều đánh giá trong thời gian ngắn';
  end if;
  return new;
end;
$$;
drop trigger if exists reviews_spam_guard on public.reviews;
create trigger reviews_spam_guard before insert on public.reviews for each row execute function public.prevent_review_spam();

