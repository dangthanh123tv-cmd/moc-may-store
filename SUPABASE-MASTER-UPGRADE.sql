-- 1) PRODUCT CATALOG — nguồn giá sản phẩm dùng chung cho mọi thiết bị.
create table if not exists public.product_catalog (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 120),
  price numeric(12,0) not null check (price >= 0 and price <= 100000000),
  category text not null check (char_length(trim(category)) between 1 and 50),
  rating numeric(2,1) not null default 5 check (rating between 0 and 5),
  description text not null default '',
  image_url text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.product_catalog enable row level security;
drop policy if exists "Cong khai xem san pham dang ban" on public.product_catalog;
drop policy if exists "Admin quan ly san pham" on public.product_catalog;
create policy "Cong khai xem san pham dang ban"
on public.product_catalog for select to anon, authenticated
using (active = true or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
create policy "Admin quan ly san pham"
on public.product_catalog for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
grant select on public.product_catalog to anon, authenticated;
grant insert, update, delete on public.product_catalog to authenticated;
grant usage, select on sequence public.product_catalog_id_seq to authenticated;

create or replace function public.set_product_updated_at()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists product_catalog_updated_at on public.product_catalog;
create trigger product_catalog_updated_at
before update on public.product_catalog
for each row execute function public.set_product_updated_at();

