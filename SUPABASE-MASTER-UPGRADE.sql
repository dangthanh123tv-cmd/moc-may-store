-- 3) SERVER-SIDE ORDER TOTAL — trình duyệt không thể tự giảm giá đơn.
create or replace function public.validate_order_total()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  item_count integer;
  distinct_count integer;
  matched_count integer;
  valid_qty boolean;
  valid_price boolean;
  calculated numeric;
  array_len integer;
begin
  if jsonb_typeof(new.items) <> 'array' then
    raise exception 'Danh sách sản phẩm không hợp lệ';
  end if;
  array_len := jsonb_array_length(new.items);
  if array_len < 1 or array_len > 30 then
    raise exception 'Danh sách sản phẩm không hợp lệ';
  end if;

  select count(*), count(distinct i.id), count(p.id),
         coalesce(bool_and(i.quantity between 1 and 99), false),
         coalesce(bool_and(i.price = p.price), false),
         coalesce(sum(p.price * i.quantity), 0)
  into item_count, distinct_count, matched_count, valid_qty, valid_price, calculated
  from jsonb_to_recordset(new.items) as i(id bigint, price numeric, quantity integer)
  left join public.product_catalog p on p.id = i.id;

  if item_count <> array_len or distinct_count <> item_count or matched_count <> array_len then
    raise exception 'Sản phẩm trong đơn không hợp lệ';
  end if;
  if not valid_qty then
    raise exception 'Số lượng sản phẩm không hợp lệ';
  end if;
  if not valid_price then
    raise exception 'Giá sản phẩm đã thay đổi. Vui lòng tải lại giỏ hàng';
  end if;
  if new.total <> calculated then
    raise exception 'Tổng đơn hàng không hợp lệ';
  end if;
  return new;
end;
$$;
drop trigger if exists orders_validate_total on public.orders;
create trigger orders_validate_total
before insert or update of items,total on public.orders
for each row execute function public.validate_order_total();

